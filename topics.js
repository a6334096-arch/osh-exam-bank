function topicForQuestion(question) {
  // The 1465-source IDs follow PDF order, including pages with repeated printed numbers.
  const sourceId = /^1465-(\d{4})$/.exec(question.id);
  if (sourceId) {
    const number = Number(sourceId[1]);
    if (number >= 1 && number <= 1479) {
      return topicSections.findLast(([start]) => number >= start)[1];
    }
  }
  // The mixed reference PDF has no topic headings. Use distinctive terms in the stem.
  const stem = (question.question || '').replace(/\s+/g, '');
  return topicRules.find(([, pattern]) => pattern.test(stem))?.[0] ?? otherTopic;
}
